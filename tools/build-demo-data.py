"""Writes assets/demo/data.js from the demo MIDI json files and cough wavs.

Run from the project root after changing anything in assets/demo/:
    python tools/build-demo-data.py

The page reads this file first, so it also works when index.html is opened
straight from disk (browsers block fetch() for file:// pages).
"""
import glob
import json
import os
import struct
import wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEMO = os.path.join(ROOT, "assets", "demo")
BUCKETS = 600


def rel(path):
    return os.path.relpath(path, ROOT).replace(os.sep, "/")


def peaks(path):
    with wave.open(path) as w:
        frames = w.readframes(w.getnframes())
        channels = w.getnchannels()
    samples = struct.unpack("<%dh" % (len(frames) // 2), frames)[::channels]
    size = max(1, len(samples) // BUCKETS)
    out = []
    for i in range(0, len(samples), size):
        chunk = samples[i:i + size]
        out.append([round(min(chunk) / 32768, 3), round(max(chunk) / 32768, 3)])
    return out


midi = {rel(p): json.load(open(p, encoding="utf-8")) for p in sorted(glob.glob(os.path.join(DEMO, "*", "*.json")))}
wave_peaks = {rel(p): peaks(p) for p in sorted(glob.glob(os.path.join(DEMO, "*", "cough-*.wav")))}

with open(os.path.join(DEMO, "data.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/build-demo-data.py. Do not edit by hand.\n")
    f.write("window.COUGHIT_DEMO = ")
    json.dump({"midi": midi, "peaks": wave_peaks}, f, separators=(",", ":"))
    f.write(";\n")

print("midi files:", len(midi), "cough waves:", len(wave_peaks))
